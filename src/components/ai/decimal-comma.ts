/** Формулалар: $$...$$ (бірнеше жол) және $...$ (бір жол) */
const MATH = /\$\$[\s\S]+?\$\$|\$[^$\n]+?\$/g;

/**
 * Қазақша ондық үтір: KaTeX «0,25»-тегі үтірді тыныс белгісі деп санап, артынан бос орын қояды да,
 * жолды сол жерден бөледі («0, 25»). Формула ішінде «цифр,цифр» → «цифр{,}цифр» — бір сан болып шығады.
 */
export const fixDecimalComma = (text: string) => text.replace(MATH, (math) => math.replace(/(\d),(?=\d)/g, "$1{,}"));
